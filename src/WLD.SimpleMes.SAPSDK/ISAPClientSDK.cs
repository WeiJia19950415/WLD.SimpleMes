         * 3. BOM明细同步接口，同步期初录入SAP中的BOM明细数据
         * BOM明细基础信息：物料名称、物料编号、规格型号、单位、使用数量、多单位下的换算方式、投入工序号
         * 3.1 注意事项,SAP的BOM明细与实际的订单BOM信息存在不一致的情况，订单BOM会根据当前是自制，外购等进行展开
         * 3.2 这里的展开方式预计为综合展开，忽略掉所有的半成品层级的中间件信息
         * 3.3 BOM明细中目前考虑只传递启用批次号、序列号管理的物料
         * 4. BOM明细调整接口【考虑覆盖方式，如果BOM明细信息调整后则整体覆盖原有的BOM数据信息】
         * **/

