         * 相关接口枚举：
         *  1. 物料信息初版同步接口,首次批量同步数据
         *  2. 物料信息单次同步接口（新增物料时，物料扩展到其他公司时）
         *  3. 物料组数据接口【批量同步接口】 分组名称
         * ***/

