        #region 20 BOM相关接口 4个

        /**
         * 基础信息(针对电池类、储能模块类的产品BOM同步)：
         * ID、物料名称、物料编号、BOM名称、BOM编号、BOM有效期、BOM类型（研发、生产）、启用状态、适用公司
         * 相关接口枚举：
         * 1. BOM同步接口，同步期初SAP录入的数据
