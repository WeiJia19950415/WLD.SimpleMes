         * 相关接口枚举：
         * 1. 可用批次物料查询接口【查询条件：入库日期，物料名称编号、供应商、批次号、公司代码等】
         * 2. 线边库库存物料查询接口【查询条件：物料名称编号】，用于判断该产线是否能使用该批次物料
         * **/
        #endregion

        #region 40 生产任务单接口 8个

        /**
         * 基础信息：
         * 任务单信息：ID、生产任务单号、物料名称、物料编号、生产数量、备注说明、项目编号、项目名称、工单状态（）、适用公司、源BOM编号，源BOMID, 生产版本记录
         * 工单BOM明细：物料名称、物料编号、规格型号、单位、使用数量、多单位下的换算方式、应用工序序号
         * 相关接口枚举：
         * 1. 期初生产任务单数据同步接口
         * 2. 期初工单BOM明细同步接口
         * 3. 生产任务单变更接口【新增时创建MES生产任务单，变更时保存数据在MES供查询用】
         * 4. 期初工单BOM变更后，对应的工单BOM明细数据是否同步？
         * 5. 工单领料过账数据查询（针对启用批次号、序列号的物料，不含反冲物料？）
         * 5.1 物料名称、物料编号、批次号、累计领料数量、单位、领料时间
         * 5.2 反冲物料如何处理？判断是否在线边库，线边库是否还有库存
         * 6. 生产报工接口【暂不考虑】
         * 7. 入库申请接口【工单编号、物料编号、序列号/批次号、数量、适用公司】
         * 8. 生产入库过账信息同步接口【用于确认序列号类型的产品是否在库】
         *  - 物料编号、序列号、入库状态
         * 
         * **/

